// 万 = 10.000：Việt Nam thường dùng K/M
const trimZero = (value: number) => value.toFixed(2).replace(/\.?0+$/, '').replace('.', ',')
const formatWan = (value: string) => {
  const n = Number(value) * 10000
  if (n >= 1e9) return `${trimZero(n / 1e9)}B`
  if (n >= 1e6) return `${trimZero(n / 1e6)}M`
  if (n >= 1e3) return `${trimZero(n / 1e3)}K`
  return String(n)
}

